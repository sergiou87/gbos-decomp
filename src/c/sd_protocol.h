#ifndef GBOS_SD_PROTOCOL_H
#define GBOS_SD_PROTOCOL_H

/* Command bytes include the SPI command prefix (0x40). */
#define SD_CMD_GO_IDLE 0x40
#define SD_CMD_SEND_OP_COND 0x41
#define SD_CMD_SEND_IF_COND 0x48
#define SD_CMD_STOP_TRANSMISSION 0x4c
#define SD_CMD_READ_MULTIPLE_BLOCK 0x52
#define SD_CMD_WRITE_MULTIPLE_BLOCK 0x59
#define SD_CMD_APP_COMMAND 0x77
#define SD_CMD_READ_OCR 0x7a
#define SD_ACMD_SEND_OP_COND 0x69

#define SD_SPI_IDLE 0xff
#define SD_RESPONSE_IDLE 1
#define SD_RESPONSE_ILLEGAL_IDLE 5
#define SD_RESPONSE_RETRIES 0x800
#define SD_CARD_UNINITIALIZED 0xff
#define SD_CARD_HIGH_CAPACITY 1
#define SD_CARD_VERSION_2 2
#define SD_OCR_HIGH_CAPACITY 0x40
#define SD_IF_COND_ARGUMENT 0x1aa
#define SD_HIGH_CAPACITY_ARGUMENT 0x40300000UL
#define SD_NO_READ_STREAM 0xffffffffUL
#define SD_SECTOR_ADDRESS_SHIFT 9

#define SD_ERR_IF_COND_TIMEOUT 0xc1
#define SD_ERR_V2_APP_COMMAND_TIMEOUT 0xc2
#define SD_ERR_V2_OP_COND_TIMEOUT 0xc3
#define SD_ERR_V2_INIT_TIMEOUT 0xc4
#define SD_ERR_OCR_TIMEOUT 0xc5
#define SD_ERR_LEGACY_APP_COMMAND_TIMEOUT 0xc6
#define SD_ERR_LEGACY_OP_COND_TIMEOUT 0xc7
#define SD_ERR_LEGACY_RETRY_APP_TIMEOUT 0xc8
#define SD_ERR_LEGACY_RETRY_OP_TIMEOUT 0xc9
#define SD_ERR_LEGACY_INIT_TIMEOUT 0xca

#endif
